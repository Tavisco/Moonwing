// Gameplay angles are clamped to -20..90 degrees. Rounding to a tenth of a
// degree changes either fixed-point coefficient by at most one unit.
func rotationCoefficients(angle float32) (sin, cos int) {
	negative := angle < 0
	if negative {
		angle = -angle
	}
	index := min(int(angle*10+0.5), len(rotationSine)-1)
	sin, cos = int(rotationSine[index]), int(rotationSine[len(rotationSine)-1-index])
	if negative {
		sin = -sin
	}
	return sin, cos
}
